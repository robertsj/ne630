#!/usr/bin/env python3
"""Plot Xe-135 (n,gamma), MT=102, from an OpenMC HDF5 neutron library.

Produces a self-contained PGFPlots .pgf plus a JSON provenance record. Import
with \\input{figures/xe135_capture.pgf}; do not resize it. Plot labels inherit
the enclosing document's text/math fonts and use a uniform 8 pt size.

Examples (use a Python environment containing OpenMC and NumPy):
  python plot_xe135_capture.py --cross-sections /data/cross_sections.xml
  python plot_xe135_capture.py --hdf5 /data/neutron/Xe135.h5
  OPENMC_CROSS_SECTIONS=/data/cross_sections.xml python plot_xe135_capture.py

No transport run, Matplotlib, TeX invocation, or repository-local Python
imports are needed. The default output directory is this script's directory.
API: https://docs.openmc.org/en/stable/pythonapi/generated/openmc.data.IncidentNeutron.html
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import sys


DEFAULT_OUTPUT = Path(__file__).resolve().with_name("xe135_capture.pgf")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def annotation_text(barns: float) -> str:
    """Use the measured value, never a hard-coded million/billion label."""
    for scale, unit in [(1e9, "billion"), (1e6, "million"), (1e3, "thousand")]:
        if barns >= scale:
            rounded = format(barns / scale, ".1g")
            return rf"$\approx {rounded}$ {unit} barns"
    return rf"$\approx {barns:.2g}$ barns"


def pgf_document(energy, capture, reference_energy: float, reference_xs: float,
                 temperature: str, data_sha: str) -> str:
    # All coordinates are evaluated from OpenMC. Preserve the native grid and
    # augment it with log-spaced points; no smoothing or invented resonances.
    coordinates = "\n".join(f"{e:.12e} {s:.12e}" for e, s in zip(energy, capture))
    lower = 10.0 ** math.floor(math.log10(float(min(capture))))
    upper = 10.0 ** math.ceil(math.log10(float(max(capture))))
    # An axis-relative note is stable if the selected energy/temperature changes.
    return rf"""% Generated by plot_xe135_capture.py; do not hand-edit numerical data.
% Xe135 capture MT=102; temperature table {temperature}; E [eV], sigma [barn].
% HDF5 SHA-256: {data_sha}
% Include with \input, not \includegraphics or \resizebox: fonts are inherited.
\begingroup
\providecolor{{wcprimary}}{{HTML}}{{512888}}
\providecolor{{wcalerted}}{{HTML}}{{CA7C1B}}
\begin{{tikzpicture}}
\begin{{loglogaxis}}[
  width=\linewidth, height=.70\linewidth,
  font=\sffamily\fontsize{{8}}{{9.5}}\selectfont,
  tick label style={{font=\sffamily\fontsize{{8}}{{9.5}}\selectfont}},
  label style={{font=\sffamily\fontsize{{8}}{{9.5}}\selectfont}},
  xlabel={{Energy, $E$ (eV)}},
  ylabel={{Capture cross section, $\sigma_\gamma(E)$ (b)}},
  xmin={energy[0]:.12e}, xmax={energy[-1]:.12e},
  ymin={lower:.12e}, ymax={upper:.12e},
  log basis x=10, log basis y=10,
  xtick={{1e-4,1e-2,1,1e2,1e4,1e6}},
  ytick={{1e-4,1e-2,1,1e2,1e4,1e6,1e8}},
  minor tick num=0, tick align=outside,
  axis line style={{black!65}}, tick style={{black!65}},
  grid=major, major grid style={{black!10,line width=.2pt}},
  clip=true,
]
\addplot[color=wcprimary,line width=.85pt,no marks]
table[row sep=newline] {{ 
energy_eV capture_b
{coordinates}
}};
\addplot[only marks,mark=*,mark size=2pt,color=wcalerted]
coordinates {{({reference_energy:.12e},{reference_xs:.12e})}};
\node[anchor=north west,align=left,text=wcalerted,
      font=\sffamily\fontsize{{8}}{{9.5}}\selectfont,
      fill=white,inner sep=2pt] (thermalnote)
  at (rel axis cs:.39,.96)
  {{{annotation_text(reference_xs)}\\at ${reference_energy:g}$ eV}};
\draw[->,>=Stealth,color=wcalerted,line width=.65pt]
  (thermalnote.north west) -- (axis cs:{reference_energy:.12e},{reference_xs:.12e});
\end{{loglogaxis}}
\end{{tikzpicture}}
\endgroup
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    inputs = parser.add_mutually_exclusive_group()
    inputs.add_argument("--cross-sections", type=Path,
                        help="OpenMC cross_sections.xml; otherwise use OpenMC's configuration/environment")
    inputs.add_argument("--hdf5", type=Path, help="direct path to Xe135.h5")
    parser.add_argument("--temperature", default="294K", help="exact HDF5 temperature key (default: 294K)")
    parser.add_argument("--annotation-energy", type=float, default=0.0253, metavar="EV")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="destination .pgf file")
    parser.add_argument("--library-label", default=None,
                        help="optional provenance label, e.g. ENDF/B-VIII.0; not inferred from arbitrary data")
    args = parser.parse_args(argv)
    if args.output.suffix.lower() != ".pgf":
        parser.error("--output must end in .pgf")
    if not math.isfinite(args.annotation_energy) or args.annotation_energy <= 0:
        parser.error("--annotation-energy must be a positive finite energy in eV")
    try:
        import numpy as np
        import openmc
        import openmc.data
    except (ImportError, OSError) as error:
        parser.error(f"OpenMC and NumPy are required; activate the OpenMC environment. {error}")

    try:
        xml_path = None
        if args.hdf5:
            data_path = args.hdf5.expanduser().resolve()
        else:
            configured = args.cross_sections or openmc.config.get("cross_sections")
            if configured is None:
                raise ValueError("supply --cross-sections or --hdf5, or set OPENMC_CROSS_SECTIONS")
            xml_path = Path(configured).expanduser().resolve()
            library = openmc.data.DataLibrary.from_xml(xml_path)
            record = library.get_by_material("Xe135", data_type="neutron")
            if record is None:
                raise ValueError(f"Xe135 neutron data are absent from {xml_path}")
            data_path = Path(record["path"]).resolve()
        nuclide = openmc.data.IncidentNeutron.from_hdf5(data_path)
        if nuclide.name != "Xe135":
            raise ValueError(f"expected Xe135 ground-state data, found {nuclide.name}")
        reaction = nuclide[102]  # radiative capture (n,gamma), not total absorption
        if args.temperature not in reaction.xs:
            raise ValueError(f"MT=102 lacks {args.temperature}; available: {', '.join(reaction.xs)}")
        function = reaction.xs[args.temperature]
        native_grid = np.asarray(function.x, dtype=float)
        lo, hi = float(native_grid[0]), float(native_grid[-1])
        if lo <= 0 or hi <= lo:
            raise ValueError("capture data have an invalid positive-energy domain")
        if not lo <= args.annotation_energy <= hi:
            raise ValueError(f"annotation energy is outside the data domain [{lo:g}, {hi:g}] eV")
        energy = np.unique(np.concatenate((native_grid, np.geomspace(lo, hi, 1600),
                                          [args.annotation_energy])))
        capture = np.asarray(function(energy), dtype=float)
        if not np.all(np.isfinite(capture) & (capture > 0)):
            raise ValueError("log plot requires finite positive capture data; no points were silently discarded")
        reference_xs = float(function(args.annotation_energy))
        data_sha = sha256(data_path)
        plot = pgf_document(energy, capture, args.annotation_energy, reference_xs,
                            args.temperature, data_sha)
        metadata = {
            "nuclide": nuclide.name, "reaction": "(n,gamma)", "mt": 102,
            "temperature_key": args.temperature, "library_label": args.library_label,
            "energy_units": "eV", "cross_section_units": "barn",
            "energy_range_eV": [lo, hi], "native_grid_points": len(native_grid),
            "plot_points": len(energy), "annotation_energy_eV": args.annotation_energy,
            "annotation_cross_section_b": reference_xs,
            "hdf5": str(data_path), "hdf5_sha256": data_sha,
            "cross_sections_xml": str(xml_path) if xml_path else None,
            "cross_sections_xml_sha256": sha256(xml_path) if xml_path else None,
            "openmc_version": openmc.__version__,
            "generator_sha256": sha256(Path(__file__)),
        }
        output = args.output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(plot, encoding="utf-8")
        output.with_suffix(".json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    except (OSError, ValueError, KeyError) as error:
        parser.error(str(error))
    print(f"Generated {output} ({len(energy)} points; Xe135 MT=102, {args.temperature})")
    print(f"sigma_gamma({args.annotation_energy:g} eV) = {reference_xs:.9g} b "
          f"= {reference_xs / 1e6:.6g} million barns")
    return 0


if __name__ == "__main__":
    sys.exit(main())
